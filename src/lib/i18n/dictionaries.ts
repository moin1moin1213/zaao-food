import { Language } from "@/services/types";

export const bengaliDigitMap: Record<string, string> = {
  "0": "০",
  "1": "১",
  "2": "২",
  "3": "৩",
  "4": "৪",
  "5": "৫",
  "6": "৬",
  "7": "৭",
  "8": "৮",
  "9": "৯",
};

export function toBengaliDigits(input: string | number): string {
  const str = String(input);
  return str.replace(/[0-9]/g, (digit) => bengaliDigitMap[digit] || digit);
}

export function formatNumber(input: number | string, lang: Language): string {
  if (lang === "bn") {
    return toBengaliDigits(input);
  }
  return String(input);
}

export function formatCurrency(amount: number, lang: Language): string {
  const formatted = formatNumber(Math.round(amount), lang);
  return `৳${formatted}`;
}

