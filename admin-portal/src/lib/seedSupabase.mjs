async function seed() {
  console.log("Seeding restaurants...");
  for (const r of restaurants) {
    const res = await sbAdmin.from("restaurants").upsert(r, { onConflict: "id" });
    if (res.error) console.error("Error upserting restaurant", r.id, res.error);
    else console.log(`✓ Restaurant [${r.id}] ${r.name_en}`);
  }

  console.log("\nSeeding riders...");
  for (const rdr of riders) {
    const res = await sbAdmin.from("riders").upsert(rdr, { onConflict: "id" });
    if (res.error) console.error("Error upserting rider", rdr.id, res.error);
    else console.log(`✓ Rider [${rdr.id}] ${rdr.name}`);
  }

  console.log("\nSeeding products...");
  for (const p of products) {
    const res = await sbAdmin.from("products").upsert(p, { onConflict: "id" });
    if (res.error) console.error("Error upserting product", p.id, res.error);
    else console.log(`✓ Product [${p.id}] ${p.name_en}`);
  }

  console.log("\nSeeding complete!");
}

seed();
